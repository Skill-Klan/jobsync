#!/usr/bin/env bash
#
# Чи цей коміт досі голова main: викладаємо лише його (D88, власник 2026-11-02).
#
# Навіщо. Рани main ідуть по черзі, і коли злиттів кілька, GitHub скасовує старші з черги — так і треба. Але
# перезапуск скасованого рану (і ран, що дочекався кнопки, коли main уже пішов далі) викладав свій, старіший образ
# поверх новішого — прод мовчки відкочувався (2026-11-02: три злиті PR зникли з проду на ~8 год). Новіший коміт
# має власний ран, і він викладе все; старшому викладати нічого.
#
# Вхід (env):
#   DEPLOY_SHA    — коміт цього рану (github.sha), 40 hex
#   DEPLOY_REMOTE — звідки читати main; за замовчуванням origin (тест — локальне голе репо)
# Вихід: `deploy=yes` або `deploy=no` у $GITHUB_OUTPUT, пояснення — в лог і в підсумок рану.
#
# 🔴 FAIL-CLOSED: не вдалось прочитати main, немає гілки, дивний SHA → крок падає (код 1), рішення не пишеться:
# без відповіді не викладаємо. Порівняння — повних SHA, дослівно.
#
# Межа: голова main — не обовʼязково найновіший образ у проді. Якщо ран голови впав, прод лишається на попередньому
# викладеному, а не на проміжному коміті: main має бути придатним до викладки на кожному коміті.

set -euo pipefail

fail() {
  echo "::error::$*"
  exit 1
}

sha="${DEPLOY_SHA:-}"
remote="${DEPLOY_REMOTE:-origin}"

[[ "$sha" =~ ^[0-9a-f]{40}$ ]] || fail "DEPLOY_SHA «${sha}» — не повний SHA коміту (40 hex)"
[ -n "${GITHUB_OUTPUT:-}" ] || fail "GITHUB_OUTPUT не заданий — рішення нікуди записати"

refs="$(git ls-remote "$remote" refs/heads/main)" || fail "не вдалось прочитати main з «${remote}» — без цього не викладаю"
head="$(printf '%s\n' "$refs" | awk '$2 == "refs/heads/main" { print $1 }')"
[[ "$head" =~ ^[0-9a-f]{40}$ ]] || fail "у «${remote}» немає гілки main — без неї не викладаю"

if [ "$head" = "$sha" ]; then
  echo "deploy=yes" >> "$GITHUB_OUTPUT"
  echo "Коміт ${sha:0:7} — голова main: викладаю."
else
  echo "deploy=no" >> "$GITHUB_OUTPUT"
  msg="Не викладаю ${sha:0:7}: main уже на ${head:0:7}, його викладе власний ран. Цей образ старіший — він відкотив би прод. Перезапускати не треба."
  echo "::notice::${msg}"
  if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
    echo "$msg" >> "$GITHUB_STEP_SUMMARY"
  fi
fi
